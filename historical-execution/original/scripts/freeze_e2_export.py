"""Create a new complete E2 export; existing exports are never replaced."""
import argparse,datetime,json,shutil,stat
from pathlib import Path
from run_experiments import ROOT,digest,read,write_json

def verify(dest):
    m=json.loads((dest/'manifest.json').read_text());actual={str(p.relative_to(dest)) for p in dest.rglob('*') if p.is_file() and p.name!='manifest.json'}
    expected={x['path'] for x in m['files']}
    # Nested source manifests are included; exclude only the export's own manifest.
    actual={str(p.relative_to(dest)) for p in dest.rglob('*') if p.is_file() and p!=dest/'manifest.json'}
    assert actual==expected,(actual-expected,expected-actual)
    for x in m['files']:
        p=dest/x['path'];assert p.stat().st_size==x['bytes'] and digest(p)==x['sha256'],x['path']
    assert m['fixed_run_count']==494 and m['model_forwards']=={'esm2_650m':217,'profam1':277}
    print(f"PASS: {len(expected)} frozen export files, exact sizes and SHA-256; 494 raw E2 arrays.")
    return len(expected)

def freeze(dest):
    assert not dest.exists(),'Never overwrite an export'
    files=set()
    def add(path):
        p=ROOT/path
        if p.is_dir():
            files.update(x for x in p.rglob('*') if x.is_file() and '__pycache__' not in x.parts)
        else:assert p.is_file(),p;files.add(p)
    for p in ['design','data/derived','sources','scripts','tests','figures','results/activations','results/qualification','environment/model-manifest.json','environment/qualification.json','environment/requirements-macmini.lock.txt','environment/macmini.sh','environment/env.sh','environment/E1-technical-plan.md','handoff/E0.json','handoff/E1.json','handoff/intake/E2.json','handoff/E1-results-and-continuation.md','handoff/E2-results-and-continuation.md','handoff/E2-execution-notes.md','handoff/E2-history']:
        add(p)
    for p in (ROOT/'results').iterdir():
        if p.is_file():files.add(p)
    for p in (ROOT/'logs').glob('E2*'):
        if p.is_file() and not p.name.startswith('E2-export'):files.add(p)
    for p in ['reviews/design-review.md','reviews/design-disposition.json','reviews/e0-review-evidence.json']:add(p)
    entries=[];dest.mkdir(parents=True)
    for source in sorted(files):
        rel=source.relative_to(ROOT);target=dest/rel;target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,target)
        h=digest(target);assert h==digest(source)
        entries.append({'path':str(rel),'source_path':str(rel),'bytes':target.stat().st_size,'sha256':h})
    # Explicitly preserve installed numerical source files without copying a portable virtual environment.
    for x in read('environment/model-manifest.json')['installed_sources']:
        source=ROOT/x['path'];rel=Path('qualified-installed-source')/Path(x['path']).relative_to('.venv-macmini/lib/python3.11/site-packages')
        target=dest/rel;target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,target)
        assert digest(target)==x['sha256'];entries.append({'path':str(rel),'source_path':x['path'],'bytes':target.stat().st_size,'sha256':x['sha256']})
    m={'schema_version':1,'export_id':'results-v1','stage':'E2','created_at':datetime.datetime.now().astimezone().isoformat(),
       'actor':'Codex /root; standalone E2 stage coordinator','status':'frozen_results_for_author_review','fixed_run_count':494,'model_forwards':{'esm2_650m':217,'profam1':277},
       'files':entries,'execution_config_sha256':digest(ROOT/'design/execution-config.json'),
       'external_model_assets':read('environment/model-manifest.json')['assets'],
       'scope':'Raw E2 activations, analysis, tables, figures, source/design records, code and checks. Weights are identified external local assets; no manuscript or publication. E0/E1 receipts preserve their original paths; historical qualification arrays are included for independent reconstruction.',
       'reproduce':'Run scripts/verify_e2.py against the two included activation manifests and results/E2-analysis-v1.json; write new output paths. Tables/figures are generated by package_e2_results.py into a new working copy. Original files stay read-only.',
       'freeze_policy':'Never edit this version. Create a new identified export for any correction.'}
    write_json(dest/'manifest.json',m)
    verify(dest)
    for p in dest.rglob('*'):
        if p.is_file():p.chmod(0o444)
    for p in sorted([p for p in dest.rglob('*') if p.is_dir()],key=lambda x:len(x.parts),reverse=True):p.chmod(0o555)
    dest.chmod(0o555)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--verify',action='store_true');a=p.parse_args();d=ROOT/'exports/results-v1'
    if a.verify:verify(d)
    else:freeze(d)
